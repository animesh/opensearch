#!/usr/bin/env python3
"""Create one provenance-aware MultiQC summary from FragPipe, Casanovo and AA_stat."""
from __future__ import annotations

import argparse
import csv
import html
import json
import re
from collections import defaultdict
from pathlib import Path

from peptide_harmonization import load_fragpipe as load_harmonized_fragpipe, load_casanovo as load_harmonized_casanovo, compare as compare_harmonized


def read_tsv(path):
    if not path or not path.exists():
        return []
    with path.open(encoding="utf-8", errors="replace", newline="") as fh:
        return list(csv.DictReader(fh, delimiter="\t"))



def parse_status(directory):
    """Read the deterministic status file emitted by each tool process."""
    status = directory / "status.tsv"
    rows = read_tsv(status)
    return rows[0] if rows else {"status": "UNKNOWN", "message": "Missing or empty status file"}


def read_manifest(directory):
    """Read the deterministic file manifest emitted by a tool process."""
    manifest = directory / "opensearch_manifest.tsv"
    rows = read_tsv(manifest)
    files = {row["role"]: directory / row["path"] for row in rows if row.get("role") and row.get("path")}
    metadata = rows[0] if rows else {}
    return metadata.get("tool", ""), metadata.get("sample", ""), files


def truth(v):
    return str(v or "").strip().lower() == "true"


def num(v, default=0.0):
    try:
        return float(v)
    except (TypeError, ValueError):
        return default


def pct(n, d):
    return 100.0 * n / d if d else 0.0


def median(values):
    values = sorted(v for v in values if v is not None)
    if not values:
        return 0.0
    n = len(values)
    return values[n // 2] if n % 2 else (values[n // 2 - 1] + values[n // 2]) / 2


def sample_name(path, suffix):
    return path.name[:-len(suffix)] if suffix and path.name.endswith(suffix) else path.name


def strip_html(text):
    return html.unescape(re.sub(r"<[^>]*>", "", text or "")).strip()


def match_pct(label):
    m = re.search(r"\(([0-9.]+)%\s+match\)", label or "")
    return float(m.group(1)) if m else None


def slug(text):
    return re.sub(r"[^A-Za-z0-9_]+", "_", text).strip("_").lower() or "section"


def write_json(name, obj):
    Path(name).write_text(json.dumps(obj, indent=2, ensure_ascii=False), encoding="utf-8")


def mqc_table(name, section, description, data):
    write_json(name, {
        "id": slug(section),
        "section_name": section,
        "description": description,
        "plot_type": "table",
        "pconfig": {"id": slug(section) + "_table"},
        "data": data,
    })


def mqc_bar(name, section, title, ylab, data):
    write_json(name, {
        "id": slug(section),
        "section_name": section,
        "plot_type": "bargraph",
        "pconfig": {"id": slug(section) + "_plot", "title": title, "ylab": ylab, "cpswitch": True},
        "data": data,
    })


def html_section(section_id, section_name, description, body):
    meta = "\n".join(["<!--", f"id: {section_id}", f"section_name: {section_name}", f"description: {description}", "-->"])
    Path(f"{section_id}_mqc.html").write_text(meta + body, encoding="utf-8")


def relative_source(tool_dir, directory, file=None):
    target = directory.name
    if file:
        rel = file.relative_to(directory)
        return f"../{tool_dir}/{target}/{rel.as_posix()}"
    return f"../{tool_dir}/{target}/"


def link(path, label):
    return f'<a href="{html.escape(path, quote=True)}">{html.escape(label)}</a>'


def parse_spectrum_key(spectrum):
    """FragPipe spectrum -> (scan, charge)."""
    m = re.search(r"\.(\d+)\.\d+\.(\d+)$", spectrum or "")
    return (int(m.group(1)), int(m.group(2))) if m else None


def parse_casanovo_key(ref, charge):
    m = re.search(r"\bscan=(\d+)", ref or "")
    return (int(m.group(1)), int(charge)) if m else None


def parse_input_spectrum_count(frag_dir, frag_files, cas_dir=None, cas_files=None, frag_dir_name="fragpipe", cas_dir_name="casanovo"):
    """Return total input spectra and provenance.

    Preferred source is spectrum_count.tsv generated by FragPipe. For existing
    results from older pipeline versions, fall back to Casanovo's explicit
    'Sequenced' + 'Skipped' log counts.
    """
    count_file = frag_files.get("spectrum_count") if frag_files else None
    if count_file:
        rows = read_tsv(count_file)
        if rows:
            r = rows[0]
            total = int(num(r.get("total_spectra"), 0))
            ms2 = int(num(r.get("ms2_spectra"), 0)) if r.get("ms2_spectra") else None
            return total, ms2, relative_source(frag_dir_name, frag_dir, count_file), "FragPipe mzML spectrum count"

    if cas_dir:
        log = cas_files.get("log") if cas_files else None
        if log:
            text = log.read_text(encoding="utf-8", errors="replace")
            seq = re.search(r"Sequenced\s+(\d+)\s+spectra", text)
            skipped = re.search(r"Skipped\s+(\d+)\s+spectra", text)
            if seq:
                ms2 = int(seq.group(1)) + (int(skipped.group(1)) if skipped else 0)
                return None, ms2, relative_source(cas_dir_name, cas_dir, log), "Casanovo sequenced + skipped MS2 spectra (total spectra unavailable)"
    return None, None, None, "Unknown"


def parse_fragpipe(directory, files, tool_dir_name):
    psm_file = files.get("psm")
    pep_file = files.get("peptide")
    prot_file = files.get("protein")
    mod_file = files.get("ptm")
    psm = read_tsv(psm_file)
    peptides = read_tsv(pep_file)
    proteins = read_tsv(prot_file)

    peptide_set = {(r.get("Peptide") or "").strip().upper() for r in peptides if r.get("Peptide") and not truth(r.get("Is Decoy")) and not truth(r.get("Is Contaminant"))}
    protein_set = {(r.get("Protein ID") or r.get("Protein") or "").strip() for r in proteins if (r.get("Protein ID") or r.get("Protein")) and not truth(r.get("Is Decoy")) and not truth(r.get("Is Contaminant"))}

    charge = defaultdict(int)
    missed = defaultdict(int)
    modified = contaminants = missed_gt0 = 0
    spectrum_keys = set()
    target_spectrum_keys = set()
    for r in psm:
        charge[str(r.get("Charge") or "?").strip()] += 1
        mc = int(num(r.get("Number of Missed Cleavages"), 0))
        missed[mc] += 1
        missed_gt0 += mc > 0
        modified += bool((r.get("Assigned Modifications") or "").strip() or (r.get("Observed Modifications") or "").strip())
        contaminants += truth(r.get("Is Contaminant"))
        key = parse_spectrum_key(r.get("Spectrum"))
        if key:
            spectrum_keys.add(key)
            if not truth(r.get("Is Decoy")) and not truth(r.get("Is Contaminant")):
                target_spectrum_keys.add(key)

    modifications = []
    if mod_file:
        for r in read_tsv(mod_file):
            name = (r.get("Modification") or "").strip()
            if not name or name.lower() == "none":
                continue
            psm_key = next((k for k in r if k.endswith("_PSMs")), None)
            pct_key = next((k for k in r if k.endswith("_percent_PSMs")), None)
            modifications.append({
                "name": name,
                "mass": num(r.get("Mass Shift")),
                "psm": int(num(r.get(psm_key), 0)),
                "pct": num(r.get(pct_key), 0),
                "isotope": "isotop" in name.lower(),
                "source": relative_source(tool_dir_name, directory, mod_file),
            })

    return {
        "program": "FragPipe", "directory": directory, "psm_file": psm_file,
        "peptide_file": pep_file, "protein_file": prot_file, "mod_file": mod_file,
        "psm": len(psm), "target_psm": sum(not truth(r.get("Is Decoy")) and not truth(r.get("Is Contaminant")) for r in psm),
        "peptide": len(peptide_set), "protein": len(protein_set),
        "modified_psm_pct": pct(modified, len(psm)), "contaminant_psm_pct": pct(contaminants, len(psm)),
        "missed_cleavage_pct": pct(missed_gt0, len(psm)), "charge": dict(charge), "missed": dict(missed),
        "peptides": peptide_set, "proteins": protein_set,
        "spectrum_keys": spectrum_keys, "target_spectrum_keys": target_spectrum_keys,
        "status": parse_status(directory),
        "unique_psm_spectra": len(spectrum_keys), "unique_target_psm_spectra": len(target_spectrum_keys),
        "modifications": modifications,
    }


def parse_casanovo(directory, files):
    log = files.get("log")
    mztab = files.get("mztab")
    text = log.read_text(encoding="utf-8", errors="replace") if log else ""
    thresholds = {}
    for threshold in ("0.00", "0.50", "0.90", "0.95", "0.99"):
        pattern = rf"([0-9]+)\s+spectra\s+\(([0-9.]+)%\)\s+scored\s+≥\s+{re.escape(threshold)}"
        m = re.search(pattern, text)
        thresholds[threshold] = (int(m.group(1)), float(m.group(2))) if m else (0, 0.0)
    m = re.search(r"Sequenced\s+([0-9]+)\s+spectra", text)
    sequenced = int(m.group(1)) if m else 0
    skipped_m = re.search(r"Skipped\s+([0-9]+)\s+spectra", text)
    skipped = int(skipped_m.group(1)) if skipped_m else 0
    sequences = set()
    q50_sequences = set()
    spectrum_keys = set()
    score_spectrum_keys = {"0.50": set(), "0.90": set(), "0.95": set(), "0.99": set()}
    mztab_psm = 0
    if mztab:
        with mztab.open(encoding="utf-8", errors="replace") as fh:
            psm_header = None
            for line in fh:
                if line.startswith("PSH\t"):
                    cols = line.rstrip("\n").split("\t")
                    psm_header = {name: i for i, name in enumerate(cols)}
                    continue
                if not line.startswith("PSM\t"):
                    continue
                mztab_psm += 1
                fields = line.rstrip("\n").split("\t")
                if len(fields) > 1:
                    seq = re.sub(r"[^A-Z]", "", fields[1].upper())
                    if seq:
                        sequences.add(seq)
                if psm_header:
                    ref_i = psm_header.get("spectra_ref")
                    charge_i = psm_header.get("charge")
                    score_i = psm_header.get("search_engine_score[1]")
                    key = None
                    if ref_i is not None and ref_i < len(fields):
                        charge = fields[charge_i] if charge_i is not None and charge_i < len(fields) else "0"
                        key = parse_casanovo_key(fields[ref_i], charge)
                    if key:
                        spectrum_keys.add(key)
                        if score_i is not None and score_i < len(fields):
                            score = num(fields[score_i], None)
                            if score is not None:
                                if score >= 0.50 and fields[1].strip():
                                    q50_sequences.add(re.sub(r"[^A-Z]", "", fields[1].upper()))
                                for threshold in score_spectrum_keys:
                                    if score >= float(threshold):
                                        score_spectrum_keys[threshold].add(key)
    sequenced = sequenced or mztab_psm
    status = parse_status(directory)
    return {
        "program": "Casanovo", "directory": directory, "log": log, "mztab": mztab,
        "sequenced": sequenced, "skipped": skipped, "thresholds": thresholds,
        "sequences": sequences, "q50_sequences": q50_sequences, "spectrum_keys": spectrum_keys, "score_spectrum_keys": score_spectrum_keys,
        "status": status,
    }


def parse_aastat(directory, files, tool_dir_name):
    stats = files.get("stats")
    inter = files.get("interpretations")
    loc = files.get("localizations")
    interpretations = json.loads(inter.read_text(encoding="utf-8")) if inter else {}
    shifts = []
    if stats:
        with stats.open(encoding="utf-8", errors="replace", newline="") as fh:
            for r in csv.DictReader(fh):
                mass = num(r.get("mass shift"), None)
                if mass is None or truth(r.get("is reference")) or num(r.get("# peptides in bin"), 0) <= 0:
                    continue
                isotope = truth(r.get("is isotope"))
                key = min(interpretations, key=lambda k: abs(num(k) - mass)) if interpretations else None
                annotations = []
                if key:
                    for item in interpretations.get(key, []):
                        if item.get("type") == "isotope":
                            continue
                        label = item.get("label", "")
                        urls = re.findall(r'href=["\']([^"\']+)', label)
                        annotations.append({"label": strip_html(label), "match": match_pct(label) or 0.0, "url": urls[0] if urls else ""})
                annotations.sort(key=lambda x: x["match"], reverse=True)
                shifts.append({"mass": mass, "npep": int(num(r.get("# peptides in bin"), 0)), "isotope": isotope,
                               "annotation": annotations[0] if annotations else {"label": "Isotope" if isotope else "Unassigned", "match": 0.0, "url": ""},
                               "source": relative_source(tool_dir_name, directory, stats)})
    localized = 0
    if loc:
        with loc.open(encoding="utf-8", errors="replace", newline="") as fh:
            for r in csv.DictReader(fh):
                if truth(r.get("is isotope")) or num(r.get("# peptides in bin"), 0) <= 0:
                    continue
                pairs = re.findall(r"['\"]([^'\"]+)['\"]\s*:\s*(\d+)", r.get("localization", ""))
                localized += any(k.lower() != "non-localized" and int(v) > 0 for k, v in pairs)
    return {"program": "AA_stat", "directory": directory, "stats": stats, "interpretations": inter, "localizations": loc,
            "shifts": shifts, "localized": localized, "status": parse_status(directory)}


def classify(summary):
    psm_med = median([v["psm"] for v in summary.values() if v["psm"]])
    q50_med = median([v["q50_pct"] for v in summary.values() if v["q50_pct"]])
    flags = {}
    for sample, v in summary.items():
        f = []
        fp_status = str(v.get("fragpipe_status", "")).upper()
        if fp_status == "FAILED":
            flags[sample] = "FRAGPIPE FAILED"
            continue
        if fp_status == "PARTIAL":
            f.append("FRAGPIPE PARTIAL")
        if psm_med and v["psm"] < 0.75 * psm_med: f.append("LOW PSM")
        if q50_med and v["q50_pct"] < 0.8 * q50_med: f.append("LOW DE NOVO")
        if v["contaminant_psm_pct"] > 2: f.append("CONTAMINANTS")
        if v["missed_cleavage_pct"] > 25: f.append("MISSED CLEAVAGE")
        flags[sample] = ", ".join(f) if f else "PASS"
    return flags


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dirs", nargs="+", required=True)
    ap.add_argument("--fragpipe_dir_name", required=True)
    ap.add_argument("--casanovo_dir_name", required=True)
    ap.add_argument("--aastat_dir_name", required=True)
    args = ap.parse_args()

    dirs = [Path(x) for x in args.dirs]
    records = []
    for directory in dirs:
        tool, sample, files = read_manifest(directory)
        if files and tool and sample:
            records.append((tool, sample, directory, files))

    frag_dirs = {s: (p, files) for tool, s, p, files in records if tool == args.fragpipe_dir_name}
    cas_dirs = {s: (p, files) for tool, s, p, files in records if tool == args.casanovo_dir_name}
    aa_dirs = {s: (p, files) for tool, s, p, files in records if tool == args.aastat_dir_name}
    frag = {s: parse_fragpipe(p, files, args.fragpipe_dir_name) for s, (p, files) in frag_dirs.items()}
    cas_all = {s: parse_casanovo(p, files) for s, (p, files) in cas_dirs.items()}
    aa_all = {s: parse_aastat(p, files, args.aastat_dir_name) for s, (p, files) in aa_dirs.items()}
    cas = {s: v for s, v in cas_all.items() if not v.get("status") or str(v.get("status", {}).get("status", "SUCCESS")).upper() in ("SUCCESS", "OK")}
    aa = {s: v for s, v in aa_all.items() if not v.get("status") or str(v.get("status", {}).get("status", "SUCCESS")).upper() in ("SUCCESS", "OK")}
    samples = sorted(set(frag) | set(cas_all) | set(aa_all))

    summary = {}
    spectrum_sources = {}
    for sample in samples:
        f, c, a = frag.get(sample, {}), cas.get(sample, {}), aa.get(sample, {})
        c_all = cas_all.get(sample, {})
        a_all = aa_all.get(sample, {})
        f_dir, f_files = frag_dirs.get(sample, (None, {}))
        c_dir, c_files = cas_dirs.get(sample, (None, {}))
        total, ms2, total_source, total_source_desc = parse_input_spectrum_count(
            f_dir, f_files, c_dir, c_files, args.fragpipe_dir_name, args.casanovo_dir_name
        ) if f_dir else (None, None, None, "Unknown")
        fp_status = f.get("status") or {}
        cas_status = c_all.get("status") or {}
        aa_status = a_all.get("status") or {}
        cseq, fpep = c.get("sequences", set()), f.get("peptides", set())
        c50 = c.get("q50_sequences", set())
        overlap = len(cseq & fpep)
        overlap50 = len(c50 & fpep)
        # Compare unique spectra, not PSM rows. FragPipe uses target/non-contaminant
        # PSM spectra; Casanovo uses spectra represented in its mzTab output.
        cas_q50_keys = c.get("score_spectrum_keys", {}).get("0.50", set())
        spectrum_both = len(cas_q50_keys & f.get("target_spectrum_keys", set()))
        cas_only_spectra = max(0, len(cas_q50_keys) - spectrum_both)
        fp_only_spectra = max(0, len(f.get("target_spectrum_keys", set())) - spectrum_both)
        q = c.get("thresholds", {})
        summary[sample] = {
            "total_spectra": total, "ms2_spectra": ms2, "spectrum_count_source": total_source_desc,
            "fragpipe_status": fp_status.get("status", "UNKNOWN"), "fragpipe_message": fp_status.get("message", ""),
            "casanovo_status": cas_status.get("status", "NOT_RUN"), "aa_stat_status": aa_status.get("status", "NOT_RUN"),
            "psm": f.get("psm", 0), "target_psm": f.get("target_psm", 0),
            "fragpipe_psm_spectra": f.get("unique_target_psm_spectra", 0),
            "peptide": f.get("peptide", 0), "protein": f.get("protein", 0),
            "fragpipe_id_pct": pct(f.get("unique_target_psm_spectra", 0), ms2 or total),
            "modified_psm_pct": f.get("modified_psm_pct", 0.0), "contaminant_psm_pct": f.get("contaminant_psm_pct", 0.0),
            "missed_cleavage_pct": f.get("missed_cleavage_pct", 0.0), "casanovo": c.get("sequenced", 0),
            "casanovo_id_pct": pct(c.get("sequenced", 0), ms2 or total), "casanovo_q50": q.get("0.50", (0, 0.0))[0],
            "casanovo_q50_pct": q.get("0.50", (0, 0.0))[1],
            "q50_pct": q.get("0.50", (0, 0.0))[1], "q90_pct": q.get("0.90", (0, 0.0))[1], "q95_pct": q.get("0.95", (0, 0.0))[1], "q99_pct": q.get("0.99", (0, 0.0))[1],
            "spectrum_both": spectrum_both, "fragpipe_only_spectra": fp_only_spectra, "casanovo_only_spectra": cas_only_spectra,
            "cas_unique": len(cseq), "overlap": overlap, "cas_only": max(0, len(cseq) - overlap), "overlap_pct": pct(overlap, len(cseq)),
            "cas_q50_unique": len(c50), "q50_overlap": overlap50, "q50_cas_only": max(0, len(c50) - overlap50), "q50_overlap_pct": pct(overlap50, len(c50)),
            "mass_shift_count": sum(not x["isotope"] for x in a.get("shifts", [])), "localized_shift_count": a.get("localized", 0),
        }
        spectrum_sources[sample] = (total_source, total_source_desc)

    # One authoritative MultiQC General Statistics table. Tool-specific generalstats
    # files are deliberately not fed to MultiQC to avoid duplicated PSM/peptide/protein columns.
    headers = {
        "total_spectra": {"title": "Total spectra", "format": "{:,.0f}"},
        "ms2_spectra": {"title": "MS2 spectra", "format": "{:,.0f}"},
        "psm": {"title": "FragPipe PSM rows", "format": "{:,.0f}"},
        "fragpipe_psm_spectra": {"title": "FragPipe PSM spectra", "format": "{:,.0f}"},
        "fragpipe_id_pct": {"title": "FragPipe ID %", "suffix": "%", "format": "{:.1f}"},
        "peptide": {"title": "Peptides", "format": "{:,.0f}"},
        "protein": {"title": "Proteins", "format": "{:,.0f}"},
    }
    if cas_all:
        headers.update({
            "casanovo": {"title": "Casanovo sequenced", "format": "{:,.0f}"},
            "casanovo_id_pct": {"title": "Casanovo sequenced %", "suffix": "%", "format": "{:.1f}"},
            "casanovo_q50": {"title": "Casanovo ≥0.5", "format": "{:,.0f}"},
            "casanovo_q50_pct": {"title": "Casanovo ≥0.5 %", "suffix": "%", "format": "{:.1f}"},
            "spectrum_both": {"title": "Both tools", "format": "{:,.0f}"},
        })
    headers.update({
        "modified_psm_pct": {"title": "Modified PSM", "suffix": "%", "format": "{:.1f}"},
        "contaminant_psm_pct": {"title": "Contaminant PSM", "suffix": "%", "format": "{:.2f}"},
        "missed_cleavage_pct": {"title": "Missed cleavage", "suffix": "%", "format": "{:.1f}"},
    })
    write_json("opensearch_generalstats_mqc.json", {
        "id": "opensearch_generalstats", "section_name": "OpenSearch Run Summary",
        "description": "One authoritative per-sample summary. Total/MS2 spectra are counted from the analysis mzML when spectrum_count.tsv is available (calibrated when possible). Older results may provide only an MS2 denominator from Casanovo sequenced + skipped spectra; this is not relabeled as total spectra.",
        "plot_type": "generalstats", "headers": headers, "data": summary,
    })

    # Optional-tool execution status. A failed optional tool is visible but does not
    # invalidate FragPipe or the other optional analyses.
    tool_status = {}
    for sample in samples:
        tool_status[sample] = {}
        for tool, source in (("FragPipe spectrum QC", frag.get(sample)), ("Casanovo", cas_all.get(sample)), ("AA_stat", aa_all.get(sample))):
            if source and source.get("status"):
                st = source["status"]
                tool_status[sample][tool] = f"{st.get('status', 'UNKNOWN')}: {st.get('message', '')}".strip()
    if any(tool_status[s] for s in tool_status):
        mqc_table("opensearch_tool_status_mqc.json", "Optional Tool Status", "Execution status of optional downstream tools. FAILED means the tool was attempted but did not produce a usable result; the remaining workflow continues.", tool_status)

    # Harmonized peptide comparison at the spectrum level. This is deliberately
    # based on the same experimental spectrum (scan + precursor charge), then
    # compares sequence and position-aware modification state separately.
    comparison_rows = []
    comparison_summary = {}
    for sample in sorted(set(frag) & set(cas)):
        fp_psm = frag[sample].get("psm_file")
        cas_mztab = cas[sample].get("mztab")
        if not fp_psm or not cas_mztab:
            continue
        fp_by_key = load_harmonized_fragpipe(fp_psm)
        cas_by_key = load_harmonized_casanovo(cas_mztab, score_threshold=0.50)
        rows, counts = compare_harmonized(fp_by_key, cas_by_key, tolerance=0.05)
        for row in rows:
            row["sample"] = sample
            comparison_rows.append(row)
        total = len(rows)
        same_seq = counts.get("same_sequence_exact_peptidoform", 0) + counts.get("same_sequence_modification_disagreement", 0)
        exact = counts.get("same_sequence_exact_peptidoform", 0)
        mod_dis = counts.get("same_sequence_modification_disagreement", 0)
        different = counts.get("different_sequence", 0)
        comparison_summary[sample] = {
            "Same spectrum": total,
            "Same sequence": same_seq,
            "Exact peptidoform": exact,
            "Same sequence, modification disagreement": mod_dis,
            "Different sequence": different,
            "Sequence agreement %": round(pct(same_seq, total), 2),
            "Peptidoform agreement %": round(pct(exact, total), 2),
        }
    if comparison_summary:
        mqc_table("opensearch_peptide_comparison_mqc.json", "Casanovo ↔ FragPipe Harmonized Peptide Comparison", "Same-spectrum comparison after filtering Casanovo to score >=0.50. Sequence identity ignores modifications; peptidoform identity additionally requires position-aware modification masses to agree within 0.05 Da. Unknown modifications are never guessed.", comparison_summary)
        with open("peptide_comparison.tsv", "w", encoding="utf-8", newline="") as fh:
            fields = ["sample", "scan", "charge", "category", "fragpipe_sequence", "casanovo_sequence", "same_sequence", "same_sequence_IL_equivalent", "fragpipe_mods", "casanovo_mods", "fragpipe_modified_peptide", "casanovo_proforma", "casanovo_score"]
            writer = csv.DictWriter(fh, fieldnames=fields, delimiter="\t")
            writer.writeheader()
            writer.writerows(comparison_rows)
        with open("peptide_comparison_summary.tsv", "w", encoding="utf-8", newline="") as fh:
            writer = csv.DictWriter(fh, fieldnames=["sample"] + list(next(iter(comparison_summary.values())).keys()), delimiter="\t")
            writer.writeheader()
            for sample, values in comparison_summary.items():
                writer.writerow({"sample": sample, **values})

    # Spectrum-level identification overview. Unlike a funnel, these categories are
    # mutually interpretable: both/FragPipe-only/Casanovo-only are based on scan+charge.
    spectrum_table = {}
    for sample, v in summary.items():
        total = v["ms2_spectra"] or v["total_spectra"]
        union = v["spectrum_both"] + v["fragpipe_only_spectra"] + v["casanovo_only_spectra"]
        neither = max(0, total - union) if total is not None else None
        spectrum_table[sample] = {
            "Input spectra": total if total is not None else "NA",
            "FragPipe PSM spectra": v["fragpipe_psm_spectra"],
            "FragPipe PSM rows": v["psm"],
            "Casanovo sequenced spectra": v["casanovo"] if sample in cas else "NA",
            "Casanovo ≥0.5 spectra": v["casanovo_q50"] if sample in cas else "NA",
            "Both tools": v["spectrum_both"] if sample in cas and sample in frag else "NA",
            "FragPipe only": v["fragpipe_only_spectra"] if sample in cas and sample in frag else "NA",
            "Casanovo only": v["casanovo_only_spectra"] if sample in cas and sample in frag else "NA",
            "Neither": neither if sample in cas and sample in frag else "NA",
        }
    mqc_table("opensearch_spectrum_identification_overview_mqc.json", "Spectrum Identification Overview", "Spectrum-level comparison of FragPipe and Casanovo. FragPipe counts unique target/non-contaminant PSM spectra; Casanovo counts spectra with score >=0.50. Both/only categories use scan number plus precursor charge.", spectrum_table)

    if frag:
        charge = {s: {f"z={k}": n for k, n in sorted(v["charge"].items(), key=lambda x: str(x[0]))} for s, v in frag.items()}
        missed = {s: {f"{k} missed": n for k, n in sorted(v["missed"].items())} for s, v in frag.items()}
        mqc_bar("opensearch_charge_mqc.json", "Precursor Charge Distribution", "FragPipe precursor charge states", "PSMs", charge)
        mqc_bar("opensearch_missed_cleavage_mqc.json", "Missed Cleavage Distribution", "FragPipe missed-cleavage counts", "PSMs", missed)

    ranked = defaultdict(int)
    for v in frag.values():
        for m in v["modifications"]:
            if not m["isotope"]: ranked[m["name"]] += m["psm"]
    top_names = [n for n, _ in sorted(ranked.items(), key=lambda x: x[1], reverse=True)[:15]]
    ptm = {name: {s: next((m["pct"] for m in frag.get(s, {}).get("modifications", []) if m["name"] == name), 0.0) for s in frag} for name in top_names}
    if ptm: mqc_bar("opensearch_ptm_shepherd_mqc.json", "PTM-Shepherd Modification Landscape", "Top non-isotope PTM-Shepherd modifications", "% of PSMs", ptm)

    if cas:
        confidence = {s: {f"≥{k}": v[1] for k, v in c["thresholds"].items()} for s, c in cas.items()}
        write_json("opensearch_casanovo_confidence_mqc.json", {"id": "opensearch_casanovo_confidence", "section_name": "Casanovo Confidence", "description": "Percentage of spectra above Casanovo confidence thresholds.", "plot_type": "linegraph", "pconfig": {"id": "opensearch_casanovo_confidence_plot", "title": "Casanovo Confidence Thresholds", "ylab": "% of sequenced spectra", "ymin": 0, "ymax": 100}, "data": confidence})
        overlap_table = {s: {"All Casanovo sequences": v["cas_unique"], "All found in FragPipe": v["overlap"], "All Casanovo-only candidates": v["cas_only"], "All overlap %": round(v["overlap_pct"], 2), "Casanovo ≥0.5 unique": v["cas_q50_unique"], "≥0.5 found in FragPipe": v["q50_overlap"], "≥0.5 Casanovo-only": v["q50_cas_only"], "≥0.5 overlap %": round(v["q50_overlap_pct"], 2)} for s, v in summary.items() if v["cas_unique"]}
        if overlap_table: mqc_table("opensearch_sequence_overlap_mqc.json", "Casanovo ↔ FragPipe Sequence Overlap", "Exact unmodified peptide-sequence overlap. The report separates all Casanovo predictions from the score ≥0.50 subset; Casanovo-only sequences are candidates, not automatically novel peptides.", overlap_table)

    aa_rows = []
    for sample, v in aa.items():
        for x in sorted((z for z in v["shifts"] if not z["isotope"]), key=lambda z: z["npep"], reverse=True)[:15]:
            ann = x["annotation"]; label = html.escape(ann["label"])
            if ann.get("url"): label = f'<a href="{html.escape(ann["url"], quote=True)}" target="_blank" rel="noopener">{label}</a>'
            aa_rows.append(f'<tr><td>{html.escape(sample)}</td><td>{x["mass"]:+.4f}</td><td>{x["npep"]:,}</td><td>{label}</td><td>{ann["match"]:.0f}%</td><td>{link(x["source"], "AA_stat")}</td></tr>')
    if aa_rows:
        html_section("opensearch_aastat_annotations", "AA_stat Mass-Shift Annotations", "AA_stat annotations with source files and reported match percentages.", '<table class="mqc-table"><thead><tr><th>Sample</th><th>Mass shift</th><th>Peptides</th><th>Annotation</th><th>Match</th><th>Source</th></tr></thead><tbody>' + "".join(aa_rows) + "</tbody></table>")

    protein_sets = {s: v["proteins"] for s, v in frag.items()}
    if len(protein_sets) > 1:
        pairs = {}; names = sorted(protein_sets)
        for i, a in enumerate(names):
            for b in names[i + 1:]:
                shared = protein_sets[a] & protein_sets[b]; union = protein_sets[a] | protein_sets[b]
                pairs[f"{a} ↔ {b}"] = {"Shared proteins": len(shared), "Union": len(union), "Jaccard %": round(pct(len(shared), len(union)), 1)}
        mqc_table("opensearch_protein_reproducibility_mqc.json", "Protein-Level Reproducibility", "Pairwise non-decoy, non-contaminant protein overlap derived from FragPipe protein.tsv.", pairs)

    flags = classify(summary)
    qc = {s: {"Status": flags[s], "Total spectra": v["total_spectra"] if v["total_spectra"] is not None else "NA", "MS2 spectra": v["ms2_spectra"] if v["ms2_spectra"] is not None else "NA", "Spectrum count source": v.get("spectrum_count_source", "Unknown"),
              "FragPipe status": v.get("fragpipe_status", "UNKNOWN"), "FragPipe PSM spectra": v["fragpipe_psm_spectra"], "FragPipe PSM rows": v["psm"],
              "FragPipe ID %": round(v["fragpipe_id_pct"], 1),
              "Modified PSMs %": round(v["modified_psm_pct"], 1), "Contaminant PSMs %": round(v["contaminant_psm_pct"], 2),
              "Missed cleavage %": round(v["missed_cleavage_pct"], 1),
              **({"Casanovo status": v.get("casanovo_status", "NOT_RUN"), "Casanovo sequenced": v["casanovo"], "Casanovo ≥0.5": v["casanovo_q50"], "Casanovo ≥0.5 %": round(v["casanovo_q50_pct"], 1), "Casanovo sequenced %": round(v["casanovo_id_pct"], 1)} if s in cas_all else {"Casanovo status": v.get("casanovo_status", "NOT_RUN")})} for s, v in summary.items()}
    mqc_table("opensearch_qc_flags_mqc.json", "Sample QC Flags", "Descriptive heuristic flags for relative run review; not acceptance criteria.", qc)

    # Provenance includes the input-spectrum denominator and the spectrum-overlap calculation.
    prov = []; source_rows = []
    for s in samples:
        f_files = frag_dirs.get(s, (None, {}))[1]
        cas_files = cas_dirs.get(s, (None, {}))[1]
        aa_files = aa_dirs.get(s, (None, {}))[1]
        if s in frag:
            f = frag[s]
            for metric, path in (("FragPipe PSMs", f["psm_file"]), ("Peptides", f["peptide_file"]), ("Proteins", f["protein_file"]), ("PTM-Shepherd modifications", f["mod_file"]), ("Input spectrum count", f_files.get("spectrum_count"))):
                if path: prov.append({"Sample": s, "Program": "FragPipe/PTM-Shepherd" if metric.startswith("PTM") else "FragPipe", "Metric": metric, "Source": relative_source(args.fragpipe_dir_name, f["directory"], path)})
        total_source, total_desc = spectrum_sources.get(s, (None, None))
        if total_source: prov.append({"Sample": s, "Program": "Input spectrum count", "Metric": "Input spectra", "Source": total_source + f" ({total_desc})"})
        if s in cas:
            c = cas[s]
            for metric, path in (("Casanovo scores", c["log"]), ("De novo sequences", c["mztab"])):
                if path: prov.append({"Sample": s, "Program": "Casanovo", "Metric": metric, "Source": relative_source(args.casanovo_dir_name, c["directory"], path)})
        if s in aa:
            a = aa[s]
            for metric, path in (("Mass shifts", a["stats"]), ("Annotations", a["interpretations"]), ("Localizations", a["localizations"])):
                if path: prov.append({"Sample": s, "Program": "AA_stat", "Metric": metric, "Source": relative_source(args.aastat_dir_name, a["directory"], path)})
        # Every artifact used by the integrated report is linked here, including
        # outputs from a tool that failed after producing partial results.
        if s in aa_all:
            a_dir = aa_all[s]["directory"]
            for role, label in (("report", "report.html"), ("stats", "aa_statistics_table.csv"),
                                ("interpretations", "interpretations.json"), ("localizations", "localization_statistics.csv")):
                path = aa_files.get(role)
                if path:
                    source_rows.append(f'<tr><td>{html.escape(s)}</td><td>AA_stat</td><td>{link(relative_source(args.aastat_dir_name, a_dir, path), label)}</td></tr>')
        if s in cas_all:
            c = cas_all[s]
            for role, label in (("log", "log"), ("mztab", "mzTab")):
                path = cas_files.get(role)
                if path:
                    source_rows.append(f'<tr><td>{html.escape(s)}</td><td>Casanovo</td><td>{link(relative_source(args.casanovo_dir_name, c["directory"], path), label)}</td></tr>')
        if s in frag:
            f = frag[s]
            for path, label in ((f["psm_file"], "psm.tsv"), (f["peptide_file"], "peptide.tsv"),
                                (f["protein_file"], "protein.tsv"), (f["mod_file"], "PTM-Shepherd global.modsummary.tsv"),
                                (f_files.get("spectrum_count"), "spectrum_count.tsv")):
                if path:
                    source_rows.append(f'<tr><td>{html.escape(s)}</td><td>FragPipe</td><td>{link(relative_source(args.fragpipe_dir_name, f["directory"], path), label)}</td></tr>')
    mqc_table("opensearch_provenance_mqc.json", "OpenSearch Data Provenance", "Every integrated metric is derived from one of the source files listed below.", {str(i + 1): r for i, r in enumerate(prov)})
    if source_rows:
        html_section("opensearch_source_reports", "Detailed Source Reports and Files", "Direct links to published source outputs used by the integrated report.", '<p>The links below point to the original files published alongside the MultiQC report.</p><table class="mqc-table"><thead><tr><th>Sample</th><th>Program</th><th>Source</th></tr></thead><tbody>' + "".join(source_rows) + "</tbody></table>")

    notes = []
    fallback_samples = [s for s, v in summary.items() if v.get("spectrum_count_source", "").startswith("Casanovo sequenced + skipped")]
    if fallback_samples:
        notes.append("<li>Input total-spectrum counts were unavailable for " + ", ".join(html.escape(x) for x in fallback_samples) + "; the reported MS2 denominator comes from Casanovo sequenced + skipped spectra and is not treated as total spectra.</li>")
    if len(summary) > 1:
        best = max(summary, key=lambda s: summary[s]["psm"]); low = min(summary, key=lambda s: summary[s]["psm"])
        notes.append(f"<li><strong>{html.escape(best)}</strong> has the highest FragPipe PSM yield ({summary[best]['psm']:,}); <strong>{html.escape(low)}</strong> has the lowest ({summary[low]['psm']:,}).</li>")
    for s, v in summary.items():
        if v["ms2_spectra"] and s in frag and s in cas:
            notes.append(f"<li><strong>{html.escape(s)}</strong>: {v['ms2_spectra']:,} MS2 spectra, {v['psm']:,} FragPipe PSMs ({v['fragpipe_id_pct']:.1f}%) and {v['casanovo']:,} Casanovo sequences ({v['casanovo_id_pct']:.1f}%). {v['spectrum_both']:,} spectra received IDs from both tools.</li>")
    html_section("opensearch_observations", "OpenSearch Observations", "Descriptive observations generated from the integrated metrics.", "<ul>" + ("".join(notes) or "<li>No observations available.</li>") + "</ul><p><em>QC flags are heuristic. Casanovo-only sequences are candidates, not automatically novel peptides.</em></p>")

    with open("summary.tsv", "w", encoding="utf-8", newline="") as fh:
        fields = ["sample"] + list(next(iter(summary.values())).keys()) if summary else ["sample"]
        writer = csv.DictWriter(fh, fieldnames=fields, delimiter="\t"); writer.writeheader()
        for sample, values in summary.items(): writer.writerow({"sample": sample, **values})
    with open("provenance.tsv", "w", encoding="utf-8", newline="") as fh:
        fields = ["Sample", "Program", "Metric", "Source"]
        writer = csv.DictWriter(fh, fieldnames=fields, delimiter="\t"); writer.writeheader(); writer.writerows(prov)


